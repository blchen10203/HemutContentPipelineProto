"""Render knowledge/fact_sheet.md from claims.yaml. The fact sheet goes whole into the system prompt.

Run from the repo root: python -m knowledge.build_fact_sheet
"""
from typing import get_args

from knowledge.loader import ROOT, load_claims
from schemas import Claim

OUT = ROOT / "knowledge" / "fact_sheet.md"
HEADINGS = {
    "price": "Prices",
    "product": "Products",
    "feature": "Features",
    "metric": "Metrics",
    "company": "Company and customers",
    "competitor": "Competitors",
}
HEADER = """<!-- GENERATED by knowledge/build_fact_sheet.py from knowledge/claims.yaml. Do not edit by hand. -->
<!-- To change it: edit claims.yaml, then run: python -m knowledge.build_fact_sheet -->

# Hemut fact sheet

Use only the quoted wordings below, with their context kept attached. Anything not here does not go in copy.
Claims under "Approval required" need human sign-off before a post may use them.
"""


def _line(c: Claim) -> str:
    text = " or ".join(f'"{p}"' for p in c.phrasings) if c.phrasings else "Record only, never use in copy."
    if c.context:
        text += f" Context: {c.context}"
    return f"- {text} `{c.id}`"


def _sections(claims: list[Claim], level: str) -> list[str]:
    out = []
    for type_ in get_args(Claim.model_fields["type"].annotation):
        group = [c for c in claims if c.type == type_]
        if group:
            out += ["", f"{level} {HEADINGS[type_]}", ""] + [_line(c) for c in group]
    return out


def render(claims: dict[str, Claim]) -> str:
    free = [c for c in claims.values() if not c.requires_approval]
    gated = [c for c in claims.values() if c.requires_approval]
    lines = [HEADER.rstrip("\n")] + _sections(free, "##")
    if gated:
        lines += ["", "## Approval required"] + _sections(gated, "###")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(render(load_claims()), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
